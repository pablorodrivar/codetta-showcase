/// <reference types="node" />
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import { type Font, parse, type PathCommand } from 'opentype.js';
import { describe, expect, it } from 'vitest';

import { TEXT_BASELINE } from '../geometry/text-and-stamps';
import { SMUFL_GLYPH_NAMES, SMUFL_GLYPHS } from './catalog';
import { SMUFL_OUTLINES, SMUFL_UNITS_PER_EM } from './generated/smufl-outlines';

const FONTS = join(import.meta.dirname, '..', '..', 'fonts');

function font(file: string): Font {
  const bytes = readFileSync(join(FONTS, file));
  return parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
}

/** One decimal: Bravura's outlines are whole font units, and 0.1 of 1000 is plenty. */
function coordinate(value: number): string {
  return String(Math.round(value * 10) / 10);
}

/** A glyph's outline as PDF path operators, in font units (`y` up), ready for `f`. */
function pathOperators(commands: readonly PathCommand[]): string {
  const parts: string[] = [];
  let x = 0;
  let y = 0;
  for (const command of commands) {
    const { x: endX = x, y: endY = y } = command;
    switch (command.type) {
      case 'M':
        parts.push(`${coordinate(endX)} ${coordinate(endY)} m`);
        break;
      case 'L':
        parts.push(`${coordinate(endX)} ${coordinate(endY)} l`);
        break;
      case 'C':
        parts.push(
          [command.x1, command.y1, command.x2, command.y2, endX, endY]
            .map((value) => coordinate(value ?? 0))
            .join(' ') + ' c',
        );
        break;
      case 'Q': {
        // CFF outlines are cubic; a quadratic one is raised to cubic all the same.
        const qx = command.x1 ?? 0;
        const qy = command.y1 ?? 0;
        parts.push(
          [
            x + ((qx - x) * 2) / 3,
            y + ((qy - y) * 2) / 3,
            endX + ((qx - endX) * 2) / 3,
            endY + ((qy - endY) * 2) / 3,
            endX,
            endY,
          ]
            .map(coordinate)
            .join(' ') + ' c',
        );
        break;
      }
      case 'Z':
        parts.push('h');
        break;
    }
    x = endX;
    y = endY;
  }
  return parts.join(' ');
}

/** The generated module, as `pnpm generate` writes it. */
function outlinesModule(bravura: Font): string {
  const entries = SMUFL_GLYPH_NAMES.map((name) => {
    const glyph = bravura.charToGlyph(String.fromCodePoint(SMUFL_GLYPHS[name]));
    const { x1, y1, x2, y2 } = glyph.getBoundingBox();
    const box = [x1, y1, x2, y2].map(coordinate).join(', ');
    return `  ${name}: {\n    box: [${box}],\n    path: '${pathOperators(glyph.path.commands)}',\n  },`;
  });
  return [
    '// Generated by src/stamps/smufl-outlines.test.ts from fonts/bravura/Bravura.otf;',
    '// do not edit. Regenerate with `pnpm generate`.',
    '//',
    '// Glyph outlines of Bravura, Copyright © 2015, Steinberg Media Technologies GmbH, with',
    '// Reserved Font Name "Bravura", under the SIL Open Font License 1.1',
    `// (fonts/bravura/OFL.txt). Not a font: the shapes of ${String(SMUFL_GLYPH_NAMES.length)} glyphs, for`,
    "// drawing stamps into an exported PDF (ADR-014) and in the app's reader.",
    "import type { SmuflGlyph } from '../catalog';",
    '',
    '/** Bravura font units per em. */',
    `export const SMUFL_UNITS_PER_EM = ${String(bravura.unitsPerEm)};`,
    '',
    '/** A SMuFL glyph as a PDF path, in font units with `y` up, and its ink box. */',
    'export interface SmuflOutline {',
    '  /** `[x0, y0, x1, y1]`, font units. */',
    '  readonly box: readonly [number, number, number, number];',
    '  /** PDF path operators (`m`, `l`, `c`, `h`), filled nonzero (`f`). */',
    '  readonly path: string;',
    '}',
    '',
    'export const SMUFL_OUTLINES: Readonly<Record<SmuflGlyph, SmuflOutline>> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

describe('SMuFL outlines for the PDF export', () => {
  const bravura = font('bravura/Bravura.otf');

  it('is up to date with Bravura and the stamp catalog', async () => {
    // Fails when the catalog or the font changes without regenerating.
    await expect(outlinesModule(bravura)).toMatchFileSnapshot('./generated/smufl-outlines.ts');
  });

  it('has an outline with ink for every stamp glyph', () => {
    expect(SMUFL_UNITS_PER_EM).toBe(1000);
    for (const name of SMUFL_GLYPH_NAMES) {
      const { box, path } = SMUFL_OUTLINES[name];
      expect(box[2] > box[0] && box[3] > box[1], name).toBe(true);
      expect(path.endsWith(' h'), name).toBe(true);
    }
  });
});

describe('TEXT_BASELINE', () => {
  it("is Inter's ascent over its ascent plus descent (hhea), the top of the em box", () => {
    const inter = font('inter/Inter-Regular.ttf');
    const { ascender, descender } = inter.tables.hhea;
    expect(TEXT_BASELINE).toBeCloseTo(ascender / (ascender - descender), 4);
  });
});
